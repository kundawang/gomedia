// ---- deterministic Ogg byte builders -------------------------------------
//
// Every test fixture is generated inside the test from fixed inputs, so the
// tests do not depend on any checked-in binary blob. The builder emits full
// Ogg pages including a correct CRC, identical in layout to real files.

// buildPage serializes one Ogg page. packets are written into the segment
// table using the standard 255-byte lacing rules; continued packets spanning
// pages are not needed by the fixtures and therefore not produced here.
func buildPage(serial, pageSeq uint32, flags byte, granule uint64, packets ...[]byte) []byte {
	var lacing []byte
	payload := make([]byte, 0)
	for _, pkt := range packets {
		remaining := len(pkt)
		for remaining >= 255 {
			lacing = append(lacing, 255)
			remaining -= 255
		}
		lacing = append(lacing, byte(remaining))
		payload = append(payload, pkt...)
	}
	if len(lacing) > 255 {
		panic("test builder: too many segments for one page")
	}
	head := make([]byte, 27)
	copy(head[0:4], CapturePattern[:])
	head[4] = 0
	head[5] = flags
	binary.LittleEndian.PutUint64(head[6:], granule)
	binary.LittleEndian.PutUint32(head[14:], serial)
	binary.LittleEndian.PutUint32(head[18:], pageSeq)
	head[26] = byte(len(lacing))
	out := make([]byte, 0, len(head)+len(lacing)+len(payload))
	out = append(out, head...)
	out = append(out, lacing...)
	out = append(out, payload...)
	// CRC over the whole page with the checksum field treated as zero.
	crcPage := make([]byte, len(out))
	copy(crcPage, out)
	binary.LittleEndian.PutUint32(crcPage[22:], 0)
	binary.LittleEndian.PutUint32(out[22:], makeChecksum(0, crcPage))
	return out
}

func opusHeadPacket(serial uint32, sampleRate, channels int) []byte {
	p := make([]byte, 19)
	copy(p, "OpusHead")
	p[8] = 1
	p[9] = byte(channels)
	binary.LittleEndian.PutUint16(p[10:], 0) // preskip
	binary.LittleEndian.PutUint32(p[12:], uint32(sampleRate))
	binary.LittleEndian.PutUint16(p[16:], 0) // output gain
	p[18] = 0                                // mapping family
	return p
}

func opusTagsPacket() []byte {
	p := make([]byte, 16)
	copy(p, "OpusTags")
	binary.LittleEndian.PutUint32(p[8:], 0) // vendor length 0
	binary.LittleEndian.PutUint32(p[12:], 0)
	return p
}

// opusPacket builds a single-frame Opus packet whose duration is fixed:
// config 0  -> 10 ms (480 samples @48kHz), config 8 -> 20 ms (960 samples).
func opusPacket(config byte, marker byte) []byte {
	return []byte{config << 3, marker}
}

// buildOpusChain builds a deterministic one-segment Opus stream.
func buildOpusChain(serial uint32, sampleRate, channels int, configs []byte, markers []byte) []byte {
	var out []byte
	head := opusHeadPacket(serial, sampleRate, channels)
	tags := opusTagsPacket()
	out = append(out, buildPage(serial, 0, 0x02, 0, head)...)
	out = append(out, buildPage(serial, 1, 0x00, 0, tags)...)
	granule := uint64(0)
	for i, cfg := range configs {
		pkt := opusPacket(cfg, markers[i])
		granule += codec.OpusPacketDuration(pkt)
		flags := byte(0x00)
		if i == len(configs)-1 {
			flags = 0x04
		}
		out = append(out, buildPage(serial, uint32(i+2), flags, granule, pkt)...)
	}
	return out
}

// ---- the original go-ogg test, driven by generated bytes -----------------

func TestDemuxer_Input(t *testing.T) {
	t.Run("ogg demux", func(t *testing.T) {
		data := buildOpusChain(0x1234, 48000, 1,
			[]byte{0, 0, 0}, []byte{0xA1, 0xA2, 0xA3})

		demuxer := NewDemuxer()
		packetCount := 0
		frameCount := 0
		demuxer.OnPacket = func(streamId uint32, granule uint64, packet []byte, lost int) {
			packetCount++
		}
		demuxer.OnFrame = func(streamId uint32, cid codec.CodecID, frame []byte, pts, dts uint64, lost int) {
			if cid != codec.CODECID_AUDIO_OPUS {
				t.Fatalf("unexpected codec %d", cid)
			}
			frameCount++
			fmt.Printf("opus frame:sid[%d] frame len:[%d] pts:[%d] dts:[%d] lost:%d\n", streamId, len(frame), pts, dts, lost)
		}
		demuxer.OnPage = func(page *oggPage) {}

		// Feed one byte at a time to exercise the page head/payload cache.
		for i := 0; i < len(data); i++ {
			if err := demuxer.Input(data[i : i+1]); err != nil {
				t.Fatalf("input at %d: %v", i, err)
			}
		}
		if err := demuxer.Flush(); err != nil {
			t.Fatalf("flush: %v", err)
		}
		if packetCount != 5 { // OpusHead + OpusTags + 3 media packets
			t.Fatalf("OnPacket count = %d, want 5", packetCount)
		}
		if frameCount != 3 {
			t.Fatalf("OnFrame count = %d, want 3", frameCount)
		}
		if p := demuxer.GetAudioParam(); p == nil || p.SampleRate != 48000 || p.ChannelCount != 1 {
			t.Fatalf("audio param wrong: %+v", p)
		}
		if demuxer.SegmentCount() != 1 {
			t.Fatalf("segment count = %d, want 1", demuxer.SegmentCount())
		}
	})
}

// ---- chained Ogg: two segments, different serial / sample rate -----------

func TestDemuxer_ChainedTwoSegments(t *testing.T) {
	// Segment 0: serial 100, 48 kHz mono, three 10 ms packets (480 each).
	seg0 := buildOpusChain(100, 48000, 1,
		[]byte{0, 0, 0}, []byte{0x11, 0x12, 0x13})
	// Segment 1: serial 200, 24 kHz stereo, two 10 ms packets (480 each).
	seg1 := buildOpusChain(200, 24000, 2,
		[]byte{8, 8}, []byte{0x21, 0x22})
	data := append(seg0, seg1...)

	demuxer := NewDemuxer()
	var begins []int
	var ends []*SegmentInfo
	var formats []*StreamFormat
	var frames []*ChainFrame
	demuxer.OnSegmentBegin = func(segment int, serial uint32) {
		begins = append(begins, segment)
	}
	demuxer.OnSegmentEnd = func(info *SegmentInfo) {
		ends = append(ends, info)
	}
	demuxer.OnStreamFormat = func(format *StreamFormat) {
		formats = append(formats, format)
	}
	demuxer.OnChainFrame = func(frame *ChainFrame) {
		cp := *frame
		frames = append(frames, &cp)
	}

	// Split the input arbitrarily across Input calls.
	mid := len(seg0) + 7
	if err := demuxer.Input(data[:mid]); err != nil {
		t.Fatal(err)
	}
	if err := demuxer.Input(data[mid:]); err != nil {
		t.Fatal(err)
	}
	if err := demuxer.Flush(); err != nil {
		t.Fatalf("flush: %v", err)
	}

	if demuxer.SegmentCount() != 2 {
		t.Fatalf("segment count = %d, want 2", demuxer.SegmentCount())
	}
	if fmt.Sprint(begins) != "[0 1]" {
		t.Fatalf("segment begins = %v, want [0 1]", begins)
	}
	if len(ends) != 2 {
		t.Fatalf("segment ends = %d, want 2", len(ends))
	}
	if ends[0].Index != 0 || ends[1].Index != 1 {
		t.Fatalf("end indexes = %d,%d", ends[0].Index, ends[1].Index)
	}
	if fmt.Sprint(ends[0].Serials) != "[100]" || fmt.Sprint(ends[1].Serials) != "[200]" {
		t.Fatalf("segment serials = %v, %v", ends[0].Serials, ends[1].Serials)
	}
	if ends[0].MissingEOS || ends[0].Truncated || ends[0].Empty {
		t.Fatalf("segment 0 flagged malformed: %+v", ends[0])
	}
	// Segment 0 duration: 1440 samples @48kHz = 30 ms.
	if ends[0].DurationMs != 30 || ends[0].BaseTimeMs != 0 {
		t.Fatalf("segment 0 timing = %+v", ends[0])
	}
	// Segment 1 starts exactly where segment 0 ended.
	if ends[1].BaseTimeMs != 30 {
		t.Fatalf("segment 1 base = %d, want 30", ends[1].BaseTimeMs)
	}
	// Segment 1 duration: 960 samples @48kHz = 20 ms.
	if ends[1].DurationMs != 20 {
		t.Fatalf("segment 1 duration = %d, want 20", ends[1].DurationMs)
	}

	if len(formats) != 2 {
		t.Fatalf("format count = %d, want 2", len(formats))
	}
	if formats[0].SampleRate != 48000 || formats[0].ChannelCount != 1 || formats[0].Changed {
		t.Fatalf("format 0 wrong: %+v", formats[0])
	}
	if formats[1].SampleRate != 24000 || formats[1].ChannelCount != 2 || !formats[1].Changed {
		t.Fatalf("format 1 must report the format change: %+v", formats[1])
	}
	if p := demuxer.GetAudioParam(); p.SampleRate != 24000 || p.ChannelCount != 2 {
		t.Fatalf("active audio param must follow latest segment: %+v", p)
	}

	// Packet order and per-segment / cumulative timestamps.
	if len(frames) != 5 {
		t.Fatalf("frame count = %d, want 5", len(frames))
	}
	wantMarkers := []byte{0x11, 0x12, 0x13, 0x21, 0x22}
	wantSeg := []int{0, 0, 0, 1, 1}
	wantSerial := []uint32{100, 100, 100, 200, 200}
	wantPtsMs := []uint64{0, 10, 20, 0, 10}        // segment-local, resets per segment
	wantTotalMs := []uint64{0, 10, 20, 30, 40}     // cumulative playback time
	for i, f := range frames {
		if f.Frame[1] != wantMarkers[i] {
			t.Fatalf("frame %d marker = %#x, want %#x", i, f.Frame[1], wantMarkers[i])
		}
		if f.Segment != wantSeg[i] || f.Serial != wantSerial[i] {
			t.Fatalf("frame %d identity = seg %d serial %d", i, f.Segment, f.Serial)
		}
		if f.SegmentPtsMs != wantPtsMs[i] {
			t.Fatalf("frame %d segment pts = %d, want %d", i, f.SegmentPtsMs, wantPtsMs[i])
		}
		if f.TotalTimeMs != wantTotalMs[i] {
			t.Fatalf("frame %d total time = %d, want %d", i, f.TotalTimeMs, wantTotalMs[i])
		}
	}
	// The second segment must not inherit the first segment's granule:
	// its first frame starts at granule 0.
	if frames[3].SegmentPts != 0 {
		t.Fatalf("segment 1 first granule = %d, want 0", frames[3].SegmentPts)
	}
	if demuxer.CumulativeTimeMs() != 50 {
		t.Fatalf("cumulative time = %d, want 50 ms", demuxer.CumulativeTimeMs())
	}
}

// ---- multiple logical streams in one segment keep their original order ---

func TestDemuxer_MultiplexedStreams(t *testing.T) {
	a := buildOpusChain(10, 48000, 1, []byte{0, 0, 0}, []byte{0xA1, 0xA2, 0xA3})
	b := buildOpusChain(11, 48000, 1, []byte{0, 0, 0}, []byte{0xB1, 0xB2, 0xB3})

	// Interleave at page granularity: BOS pages first (a then b), then data
	// pages interleaved, then EOS pages interleaved.
	pagesA := splitPages(t, a)
	pagesB := splitPages(t, b)
	var data []byte
	data = append(data, pagesA[0]...) // BOS a (order 0)
	data = append(data, pagesB[0]...) // BOS b (order 1)
	data = append(data, pagesA[1]...) // tags a
	data = append(data, pagesB[1]...) // tags b
	data = append(data, pagesA[2]...)
	data = append(data, pagesB[2]...)
	data = append(data, pagesA[3]...)
	data = append(data, pagesB[3]...)
	data = append(data, pagesA[4]...) // EOS a
	data = append(data, pagesB[4]...) // EOS b

	demuxer := NewDemuxer()
	var orders []int
	var markers []byte
	var serials []uint32
	demuxer.OnStreamFormat = func(format *StreamFormat) {
		orders = append(orders, format.StreamOrder)
		serials = append(serials, format.Serial)
	}
	demuxer.OnChainFrame = func(frame *ChainFrame) {
		markers = append(markers, frame.Frame[1])
	}
	if err := demuxer.Input(data); err != nil {
		t.Fatal(err)
	}
	if err := demuxer.Flush(); err != nil {
		t.Fatalf("flush: %v", err)
	}
	if fmt.Sprint(orders) != "[0 1]" || fmt.Sprint(serials) != "[10 11]" {
		t.Fatalf("logical stream order lost: orders %v serials %v", orders, serials)
	}
	// Physical interleaving order is preserved for frames.
	if fmt.Sprint(markers) != "[161 177 162 178 163 179]" {
		t.Fatalf("frame order = %v, want interleaved", markers)
	}
	if demuxer.SegmentCount() != 1 {
		t.Fatalf("segment count = %d, want 1", demuxer.SegmentCount())
	}
}

func splitPages(t *testing.T, data []byte) [][]byte {
	t.Helper()
	var pages [][]byte
	off := 0
	for off < len(data) {
		if !bytes.Equal(data[off:off+4], CapturePattern[:]) {
			t.Fatal("fixture is not page aligned")
		}
		segCount := int(data[off+26])
		pageLen := 27 + segCount
		for i := 0; i < segCount; i++ {
			pageLen += int(data[off+27+i])
		}
		pages = append(pages, data[off:off+pageLen])
		off += pageLen
	}
	return pages
}

// ---- malformed input: deterministic continue / error rules ---------------

func TestDemuxer_MissingEOS(t *testing.T) {
	// Build a normal chain then strip the EOS flag from the final page.
	data := buildOpusChain(30, 48000, 1, []byte{0, 0}, []byte{0xC1, 0xC2})
	last := bytes.LastIndex(data, CapturePattern[:])
	data[last+5] &^= 0x04

	demuxer := NewDemuxer()
	var end *SegmentInfo
	demuxer.OnSegmentEnd = func(info *SegmentInfo) {
		end = info
	}
	frames := 0
	demuxer.OnChainFrame = func(frame *ChainFrame) {
		frames++
	}
	if err := demuxer.Input(data); err != nil {
		t.Fatalf("input must keep going: %v", err)
	}
	err := demuxer.Flush()
	if !errors.Is(err, ErrMissingEOS) {
		t.Fatalf("flush err = %v, want ErrMissingEOS", err)
	}
	if end == nil || !end.MissingEOS || end.Empty {
		t.Fatalf("segment end info wrong: %+v", end)
	}
	if frames != 2 {
		t.Fatalf("frames delivered = %d, want 2", frames)
	}
}

func TestDemuxer_MissingEOSMidStream(t *testing.T) {
	// Segment 0 is missing its EOS: a BOS of the next segment finalizes it
	// with MissingEOS and parsing continues into segment 1.
	seg0 := buildOpusChain(31, 48000, 1, []byte{0}, []byte{0xF1})
	last := bytes.LastIndex(seg0, CapturePattern[:])
	seg0[last+5] &^= 0x04
	seg1 := buildOpusChain(32, 48000, 1, []byte{0}, []byte{0xF2})

	demuxer := NewDemuxer()
	var ends []*SegmentInfo
	var frameSegs []int
	demuxer.OnSegmentEnd = func(info *SegmentInfo) {
		ends = append(ends, info)
	}
	demuxer.OnChainFrame = func(frame *ChainFrame) {
		frameSegs = append(frameSegs, frame.Segment)
	}
	if err := demuxer.Input(append(seg0, seg1...)); err != nil {
		t.Fatalf("a missing EOS must not stop the chain: %v", err)
	}
	if err := demuxer.Flush(); err != nil {
		t.Fatalf("segment 1 is properly closed, flush err = %v", err)
	}
	if len(ends) != 2 {
		t.Fatalf("segments ended = %d, want 2", len(ends))
	}
	if !ends[0].MissingEOS {
		t.Fatalf("segment 0 must be flagged MissingEOS: %+v", ends[0])
	}
	if ends[1].MissingEOS {
		t.Fatalf("segment 1 must be clean: %+v", ends[1])
	}
	if fmt.Sprint(frameSegs) != "[0 1]" {
		t.Fatalf("frames must be delivered from both segments: %v", frameSegs)
	}
}

func TestDemuxer_DuplicateBOS(t *testing.T) {
	head := buildPage(40, 0, 0x02, 0, opusHeadPacket(40, 48000, 1))
	tags := buildPage(40, 1, 0x00, 0, opusTagsPacket())
	dup := buildPage(40, 2, 0x02, 0, opusHeadPacket(40, 48000, 1))

	demuxer := NewDemuxer()
	if err := demuxer.Input(append(append(head, tags...), dup...)); !errors.Is(err, ErrDuplicateBOS) {
		t.Fatalf("err = %v, want ErrDuplicateBOS", err)
	}
}

func TestDemuxer_TruncatedTail(t *testing.T) {
	data := buildOpusChain(50, 48000, 1, []byte{0}, []byte{0xD1})
	cut := len(data) / 2

	demuxer := NewDemuxer()
	var end *SegmentInfo
	demuxer.OnSegmentEnd = func(info *SegmentInfo) {
		end = info
	}
	if err := demuxer.Input(data[:cut]); err != nil {
		t.Fatalf("partial input must be buffered, got %v", err)
	}
	err := demuxer.Flush()
	if !errors.Is(err, ErrTruncatedPage) {
		t.Fatalf("flush err = %v, want ErrTruncatedPage", err)
	}
	if end == nil || !end.Truncated {
		t.Fatalf("segment end must be marked truncated: %+v", end)
	}
}

func TestDemuxer_EmptySegment(t *testing.T) {
	// BOS + header + EOS, no media packet.
	head := buildPage(60, 0, 0x02, 0, opusHeadPacket(60, 48000, 1))
	eos := buildPage(60, 1, 0x04, 0)
	demuxer := NewDemuxer()
	var end *SegmentInfo
	demuxer.OnSegmentEnd = func(info *SegmentInfo) {
		end = info
	}
	if err := demuxer.Input(append(head, eos...)); err != nil {
		t.Fatal(err)
	}
	if err := demuxer.Flush(); err != nil {
		t.Fatalf("empty segment must flush cleanly, got %v", err)
	}
	if end == nil || !end.Empty {
		t.Fatalf("segment must be reported empty: %+v", end)
	}
}

func TestDemuxer_SerialReuse(t *testing.T) {
	// Two chained segments reusing serial 70; the second segment resets its
	// page sequence, which must not be reported as a lost page.
	seg0 := buildOpusChain(70, 48000, 1, []byte{0}, []byte{0xE1})
	seg1 := buildOpusChain(70, 16000, 1, []byte{0}, []byte{0xE2})

	demuxer := NewDemuxer()
	var ends []*SegmentInfo
	var formats []*StreamFormat
	var frames []*ChainFrame
	demuxer.OnSegmentEnd = func(info *SegmentInfo) {
		ends = append(ends, info)
	}
	demuxer.OnStreamFormat = func(format *StreamFormat) {
		formats = append(formats, format)
	}
	demuxer.OnChainFrame = func(frame *ChainFrame) {
		cp := *frame
		frames = append(frames, &cp)
	}
	if err := demuxer.Input(append(seg0, seg1...)); err != nil {
		t.Fatal(err)
	}
	if err := demuxer.Flush(); err != nil {
		t.Fatalf("flush: %v", err)
	}
	if len(ends) != 2 {
		t.Fatalf("segments = %d, want 2", len(ends))
	}
	if len(ends[1].SerialReused) != 1 || ends[1].SerialReused[0] != 70 {
		t.Fatalf("serial reuse not recorded: %+v", ends[1])
	}
	if len(frames) != 2 || frames[0].Lost != 0 || frames[1].Lost != 0 {
		t.Fatalf("reused serial produced loss/wrong frames: %+v", frames)
	}
	if frames[1].Segment != 1 || frames[1].SegmentPts != 0 {
		t.Fatalf("reused segment must restart granule at 0: %+v", frames[1])
	}
	if len(formats) != 2 || !formats[1].Changed || formats[1].SampleRate != 16000 {
		t.Fatalf("reused serial format change wrong: %+v", formats)
	}
}

// ---- fixture validity: the generated bytes are real Ogg for ffmpeg -------

func TestDemuxer_FixturesAreValidOgg(t *testing.T) {
	ffmpeg, err := exec.LookPath("ffmpeg")
	if err != nil {
		t.Skip("ffmpeg not available")
	}
	seg0 := buildOpusChain(100, 48000, 1, []byte{0, 0, 0}, []byte{0x11, 0x12, 0x13})
	seg1 := buildOpusChain(200, 24000, 2, []byte{8, 8}, []byte{0x21, 0x22})
	dir := t.TempDir()
	path := filepath.Join(dir, "chained.ogg")
	if err := os.WriteFile(path, append(seg0, seg1...), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(ffmpeg, "-hide_banner", "-loglevel", "error", "-i", path, "-f", "null", os.DevNull)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("ffmpeg rejects the chained fixture: %v\n%s", err, out)
	}
}
